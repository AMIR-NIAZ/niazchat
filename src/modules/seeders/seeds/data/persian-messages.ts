/**
 * Typed content for the development demo seeder.
 *
 * Everything that ends up in the database (users, groups, chat text) lives
 * here so the seeder itself stays logic-only. The text is intentionally varied:
 * short/long, emoji, numbers, links, English words and multi-line messages.
 */

export interface DemoUserSeed {
    name: string;
    username: string;
    /** Deterministic E.164 Iranian mobile number. */
    phone: string;
}

export interface DemoAdminSeed {
    username: string;
    /** One of `all` | `ban_user` | `change_info_chat` | `delete_message`. */
    permission: DemoPermission;
}

export type DemoPermission =
    | 'all'
    | 'ban_user'
    | 'change_info_chat'
    | 'delete_message';

export interface DemoGroupSeed {
    title: string;
    description: string;
    /** Final membership rows, including me and any banned member. */
    memberCount: number;
    /** My role in this group. */
    myRole: 'manager' | 'admin' | 'user';
    manager: string;
    admins: DemoAdminSeed[];
    /** Present only on the group that demonstrates the banned-users screen. */
    banned?: string;
    /** A demo user who leaves the group during the seeded history. */
    leaver: string;
    /** 40-120. */
    messageCount: number;
    /** Unread messages for me after seeding (0-12). */
    unreadForMe: number;
}

